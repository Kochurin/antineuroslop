function ruleIds(text) {
  return AS.analyze(text).matches.map((m) => m.rule);
}
function rawHits(id, text) {
  // Проверяем правило без конкуренции с другими: остальные выключены
  const disabled = {};
  AS.rules.forEach((r) => { if (r.id !== id) disabled[r.id] = 1; });
  disabled.rhythm = 1;
  return AS.analyze(text, { disabled }).matches.length;
}

test('у каждого правила есть примеры', () => {
  const missing = AS.rules.map((r) => r.id).filter((id) => !CASES[id]);
  assert.deepEqual(missing, []);
});

for (const [id, c] of Object.entries(CASES)) {
  test(`${id}: срабатывает на штампах`, () => {
    for (const s of c.bad) assert.ok(rawHits(id, s) > 0, `не нашёл в: ${s}`);
  });
  test(`${id}: молчит на нормальном тексте`, () => {
    for (const s of c.good) assert.equal(rawHits(id, s), 0, `ложное срабатывание в: ${s}`);
  });
}

test('живой текст получает высокую оценку', () => {
  const human = 'Вчера полдня чинил роутер. Оказалось, провайдер сменил DNS и никому не сказал. Позвонил в поддержку, там девушка долго извинялась и дала промокод на месяц';
  const r = AS.analyze(human);
  assert.ok(r.score >= 85, `оценка ${r.score}, нашёл: ${r.matches.map((m) => m.rule)}`);
});

test('нейрослоп получает низкую оценку', () => {
  const slop = 'В современном мире VPN — это не просто инструмент, а настоящий незаменимый помощник. Давайте разберёмся, почему это важно. Важно отметить, что данный сервис является быстрым, надёжным и удобным. В заключение, это меняет правила игры.';
  const r = AS.analyze(slop);
  assert.ok(r.score < 40, `оценка ${r.score}`);
  assert.equal(r.verdict.label, 'Нейрослоп');
});

test('пустой текст', () => {
  const r = AS.analyze('');
  assert.equal(r.score, 100);
  assert.equal(r.matches.length, 0);
});

test('ровный ритм замечается как общий признак', () => {
  const t = 'Мы запустили новый сервис для малого бизнеса. Он помогает вести учёт товаров на складе. Клиенты получают отчёты каждую неделю по почте. Команда отвечает на вопросы в течение часа. Тарифы начинаются от трёхсот рублей в месяц';
  const r = AS.analyze(t);
  assert.ok(r.notes.some((n) => n.id === 'rhythm'));
});

function fixFirst(text, id, k = 0) {
  const m = AS.analyze(text).matches.find((x) => x.rule === id);
  assert.ok(m, `нет совпадения ${id} в: ${text}`);
  return AS.fixText(text, m, m.fixes[k]);
}

test('удаление вводной фразы поднимает регистр', () => {
  assert.equal(fixFirst('Важно отметить, что цены растут', 'vazhno-otmetit'), 'Цены растут');
});

test('удаление усилителя не оставляет двойных пробелов', () => {
  assert.equal(fixFirst('Это действительно работает', 'intensifier'), 'Это работает');
});

test('удаление в конце строки не оставляет запятую', () => {
  assert.equal(fixFirst('Работает отлично, безусловно\nВторая строка', 'intensifier'), 'Работает отлично\nВторая строка');
});

test('замена канцелярита сохраняет регистр', () => {
  assert.equal(fixFirst('На сегодняшний день цены выросли', 'kanc'), 'Сейчас цены выросли');
  assert.equal(fixFirst('Цены на сегодняшний день выросли', 'kanc'), 'Цены сейчас выросли');
});

test('тире меняется на запятую и на точку с заглавной', () => {
  assert.equal(fixFirst('Москва — столица', 'em-dash', 0), 'Москва, столица');
  assert.equal(fixFirst('Пришёл — увидел', 'em-dash', 1), 'Пришёл. Увидел');
});

test('точка в конце строки убирается', () => {
  assert.equal(fixFirst('Сеть есть. Интернет тоже.', 'final-period'), 'Сеть есть. Интернет тоже');
});

test('«Давайте разберёмся» удаляется целиком', () => {
  assert.equal(fixFirst('Давайте разберёмся, как это работает', 'davaite'), 'Как это работает');
});

test('пропущенное совпадение больше не показывается', () => {
  const t = 'Это действительно важно';
  const m = AS.analyze(t).matches[0];
  const r = AS.analyze(t, { ignored: { [m.key]: 1 } });
  assert.equal(r.matches.filter((x) => x.key === m.key).length, 0);
});

test('совпадения не пересекаются', () => {
  const t = 'В современном мире VPN — это не просто инструмент, а незаменимый помощник. Важно отметить, что данный сервис является быстрым, надёжным и удобным';
  const ms = AS.analyze(t).matches;
  for (let i = 1; i < ms.length; i++) assert.ok(ms[i].start >= ms[i - 1].end, 'пересечение');
});

test('длинный текст разбирается быстро', () => {
  const big = 'Важно отметить, что данный сервис действительно является удобным — проверено. '.repeat(300);
  const t0 = Date.now();
  AS.analyze(big);
  assert.ok(Date.now() - t0 < 1500, 'медленно');
});
